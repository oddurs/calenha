"""Turning the language into things people read: a Markdown dictionary and a web page."""

from __future__ import annotations

import html
import unicodedata
from datetime import date
from importlib import resources
from string import Template

from .language import Entry, Language
from .phonology import BREATH, PhonologyError, Word
from .validate import words_of

POS_LABEL = {
    "noun": "noun",
    "verb": "verb",
    "adjective": "quality",
    "name": "name",
    "particle": "particle",
    "pronoun": "person",
}


def collate(word: str) -> str:
    """Alphabetical order ignores accents: célë sorts with cela, not after z."""
    stripped = unicodedata.normalize("NFD", word)
    return "".join(ch for ch in stripped if not unicodedata.combining(ch))


def sorted_entries(language: Language) -> list[Entry]:
    return sorted(language.entries, key=lambda e: (collate(e.word), e.word, e.pos))


def stats(language: Language) -> dict[str, int]:
    return {
        "words": len(language.entries),
        "roots": len(language.roots),
        "phrases": len(language.phrases),
        "old forms": sum(1 for e in language.entries if e.old),
    }


def explain_parts(entry: Entry, language: Language) -> list[tuple[str, str]]:
    """Each morpheme of a word with its meaning: [('thal', 'flow, moving water'), …]."""
    out = []
    for part in entry.parts:
        if part in language.roots:
            out.append((part, language.roots[part].meaning))
        elif affixes := language.affix(part):
            match = next((a for a in affixes if a.makes == entry.pos), affixes[0])
            out.append((part, match.meaning.split(".")[0]))
        elif parents := language.lookup(part):
            out.append((part, parents[0].gloss))
        else:
            out.append((part, ""))
    return out


# -- markdown -------------------------------------------------------------------


def markdown(language: Language) -> str:
    counts = stats(language)
    lines = [
        "# Calenha — dictionary",
        "",
        "*the calm speech of the Calenhi of Solmara*",
        "",
        f"{counts['words']} words, grown from {counts['roots']} roots. "
        "Generated by `calenha build` from `lang/` — do not edit by hand.",
        "Stressed syllables are in capitals.",
        "",
    ]
    letter = ""
    for entry in sorted_entries(language):
        initial = collate(entry.word)[0]
        if initial != letter:
            letter = initial
            lines += [f"## {letter}", ""]
        word = language.phonology.syllabify(entry.word)
        block = [
            f"**{entry.word}** ({word.hyphenated('-')}) /{word.ipa()}/ "
            f"*{POS_LABEL[entry.pos]}* — {entry.gloss}"
        ]
        if entry.sense:
            block.append(f"*{entry.sense}*")
        if entry.parts:
            parts = " + ".join(f"{p} ({m})" if m else p for p, m in explain_parts(entry, language))
            block.append(f"from {parts}")
        if entry.old:
            block.append(f"older \\*{entry.old}")
        lines += ["  \n".join(block), ""]

    lines += ["## in use", ""]
    for phrase in language.phrases:
        lines += [
            f"> **{phrase.text}**  ",
            f"> {phrase.literal}  ",
            f"> *{phrase.translation}*",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


# -- html -----------------------------------------------------------------------


def stressed_html(word: Word, shown: str | None = None) -> str:
    """A word as written, with its stressed syllable wrapped for the gold mark.

    ``shown`` keeps the capitals and breath marks of the original spelling.
    """
    shown = shown or word.text
    target = len(word.text)
    # map each letter of the plain word to its position in the shown spelling
    positions = [i for i, ch in enumerate(shown) if ch != BREATH]
    if len(positions) != target:
        return html.escape(shown)
    start = sum(len(s.text) for s in word.syllables[: word.stress])
    end = start + len(word.syllables[word.stress].text)
    if len(word.syllables) == 1:
        return html.escape(shown)
    a, b = positions[start], positions[end - 1] + 1
    return (
        html.escape(shown[:a])
        + f'<span class="st">{html.escape(shown[a:b])}</span>'
        + html.escape(shown[b:])
    )


def line_html(text: str, language: Language) -> str:
    """A line of Calenha with stress marked on every word and breaths set apart."""
    out = []
    for i, token in enumerate(text.split()):
        core = token.strip(".,;:!?")
        lead, trail = token[: token.index(core)] if core else "", token[len(core) :] if core else ""
        if token == BREATH:
            piece = f'<span class="breath">{BREATH}</span>'
        elif core and words_of(core):
            try:
                word = language.phonology.syllabify(core)
                piece = html.escape(lead) + stressed_html(word, core) + html.escape(trail)
            except PhonologyError:
                piece = html.escape(token)
            piece = piece.replace(BREATH, f'<span class="breath">{BREATH}</span>')
        else:
            piece = html.escape(token)
        out.append(f'<span class="w" style="--i:{i}">{piece}</span>')
    return " ".join(out)


def entry_html(entry: Entry, language: Language) -> str:
    word = language.phonology.syllabify(entry.word)
    search = " ".join(
        filter(None, [entry.word, collate(entry.word), entry.gloss, entry.sense or ""])
    ).lower()
    bits = [
        f'<article class="entry" data-domain="{entry.domain}" '
        f'data-search="{html.escape(search)}" id="w-{html.escape(collate(entry.word))}">',
        f'<h4 class="hw" lang="x-calenha">{stressed_html(word)}</h4>',
        '<div class="body">',
        f'<p class="gloss">{html.escape(entry.gloss)}'
        f' <span class="pos">{POS_LABEL[entry.pos]}</span></p>',
        f'<p class="ipa">/{html.escape(word.ipa())}/</p>',
    ]
    if entry.sense:
        bits.append(f'<p class="sense">{html.escape(entry.sense)}</p>')
    if entry.parts or entry.old:
        ety = []
        if entry.parts:
            ety.append(
                " + ".join(
                    f'<span lang="x-calenha">{html.escape(p)}</span>'
                    + (f" <i>{html.escape(m)}</i>" if m else "")
                    for p, m in explain_parts(entry, language)
                )
            )
        if entry.old:
            ety.append(f'from older <span lang="x-calenha">*{html.escape(entry.old)}</span>')
        bits.append(f'<p class="ety">{"; ".join(ety)}</p>')
    bits += ["</div>", "</article>"]
    return "\n".join(bits)


def page(language: Language, *, standalone: bool = True) -> str:
    """The dictionary as one self-contained page.

    ``standalone`` wraps it in a full document; without it, the page is a fragment
    for hosts that supply their own document shell.
    """
    counts = stats(language)
    featured = next((p for p in language.phrases if p.featured), language.phrases[0])

    phrases = "\n".join(
        f'<li><p class="cal" lang="x-calenha">{line_html(p.text, language)}</p>'
        f'<p class="lit">{html.escape(p.literal)}</p>'
        f'<p class="tr">{html.escape(p.translation)}</p></li>'
        for p in language.phrases
        if p is not featured
    )

    groups, letter, current = [], "", []
    for entry in sorted_entries(language):
        initial = collate(entry.word)[0]
        if initial != letter and current:
            groups.append((letter, current))
            current = []
        letter = initial
        current.append(entry_html(entry, language))
    groups.append((letter, current))
    dictionary = "\n".join(
        f'<section class="letter" data-letter="{lt}"><h3>{lt}</h3>{"".join(items)}</section>'
        for lt, items in groups
    )

    domains = "\n".join(
        f'<button type="button" class="chip" id="d-{d}" data-domain="{d}" aria-pressed="false">'
        f"{d}</button>"
        for d in language.domains
    )

    template = Template(resources.files("calenha").joinpath("page.html").read_text("utf-8"))
    body = template.substitute(
        hero=line_html(featured.text, language),
        hero_translation=html.escape(featured.translation),
        phrases=phrases,
        dictionary=dictionary,
        domains=domains,
        words=counts["words"],
        roots=counts["roots"],
        built=date.today().isoformat(),
    )
    if not standalone:
        return body
    head, _, content = body.partition("<!-- body -->")
    return (
        '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        f"{head.strip()}\n</head>\n<body>{content.rstrip()}\n</body>\n</html>\n"
    )
