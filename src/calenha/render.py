"""Turning the language into things people read: shared helpers and the Markdown dictionary."""

from __future__ import annotations

import html
import unicodedata
from collections.abc import Callable

from .language import Entry, Language
from .phonology import BREATH, PhonologyError, Word
from .validate import words_of

POS_LABEL = {
    "noun": "noun",
    "verb": "verb",
    "adjective": "quality",
    "name": "name",
    "particle": "particle",
    "pronoun": "person",
}


def collate(word: str) -> str:
    """Alphabetical order ignores accents: célë sorts with cela, not after z."""
    stripped = unicodedata.normalize("NFD", word)
    return "".join(ch for ch in stripped if not unicodedata.combining(ch))


def sorted_entries(language: Language) -> list[Entry]:
    return sorted(language.entries, key=lambda e: (collate(e.word), e.word, e.pos))


def stats(language: Language) -> dict[str, int]:
    return {
        "words": len(language.entries),
        "roots": len(language.roots),
        "phrases": len(language.phrases),
        "old forms": sum(1 for e in language.entries if e.old),
    }


def explain_parts(entry: Entry, language: Language) -> list[tuple[str, str]]:
    """Each morpheme of a word with its meaning: [('thal', 'flow, moving water'), …]."""
    out = []
    for part in entry.parts:
        if part in language.roots:
            out.append((part, language.roots[part].meaning))
        elif affixes := language.affix(part):
            match = next((a for a in affixes if a.makes == entry.pos), affixes[0])
            out.append((part, match.meaning.split(".")[0]))
        elif parents := language.lookup(part):
            out.append((part, parents[0].gloss))
        else:
            out.append((part, ""))
    return out


# -- markdown -------------------------------------------------------------------


def markdown(language: Language) -> str:
    counts = stats(language)
    lines = [
        "# Calenha — dictionary",
        "",
        "*the calm speech of the Calenhi of Solmara*",
        "",
        f"{counts['words']} words, grown from {counts['roots']} roots. "
        "Generated by `calenha build` from `lang/` — do not edit by hand.",
        "Stressed syllables are in capitals.",
        "",
    ]
    letter = ""
    for entry in sorted_entries(language):
        initial = collate(entry.word)[0]
        if initial != letter:
            letter = initial
            lines += [f"## {letter}", ""]
        word = language.phonology.syllabify(entry.word)
        block = [
            f"**{entry.word}** ({word.hyphenated('-')}) /{word.ipa()}/ "
            f"*{POS_LABEL[entry.pos]}* — {entry.gloss}"
        ]
        if entry.sense:
            block.append(f"*{entry.sense}*")
        if entry.parts:
            parts = " + ".join(f"{p} ({m})" if m else p for p, m in explain_parts(entry, language))
            block.append(f"from {parts}")
        if entry.old:
            block.append(f"older \\*{entry.old}")
        lines += ["  \n".join(block), ""]

    lines += ["## in use", ""]
    for phrase in language.phrases:
        lines += [
            f"> **{phrase.text}**  ",
            f"> {phrase.literal}  ",
            f"> *{phrase.translation}*",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


# -- html -----------------------------------------------------------------------


def stressed_html(word: Word, shown: str | None = None) -> str:
    """A word as written, with its stressed syllable wrapped for the gold mark.

    ``shown`` keeps the capitals and breath marks of the original spelling.
    """
    shown = shown or word.text
    target = len(word.text)
    # map each letter of the plain word to its position in the shown spelling
    positions = [i for i, ch in enumerate(shown) if ch != BREATH]
    if len(positions) != target:
        return html.escape(shown)
    start = sum(len(s.text) for s in word.syllables[: word.stress])
    end = start + len(word.syllables[word.stress].text)
    if len(word.syllables) == 1:
        return html.escape(shown)
    a, b = positions[start], positions[end - 1] + 1
    return (
        html.escape(shown[:a])
        + f'<span class="st">{html.escape(shown[a:b])}</span>'
        + html.escape(shown[b:])
    )


def line_html(
    text: str, language: Language, href: Callable[[str], str | None] | None = None
) -> str:
    """A line of Calenha with stress marked on every word and breaths set apart.

    ``href`` may give a link for each word (by its plain spelling).
    """
    out = []
    for i, token in enumerate(text.split()):
        core = token.strip(".,;:!?")
        lead, trail = token[: token.index(core)] if core else "", token[len(core) :] if core else ""
        if token == BREATH:
            piece = f'<span class="breath">{BREATH}</span>'
        elif core and words_of(core):
            try:
                word = language.phonology.syllabify(core)
                piece = html.escape(lead) + stressed_html(word, core) + html.escape(trail)
            except PhonologyError:
                piece = html.escape(token)
            piece = piece.replace(BREATH, f'<span class="breath">{BREATH}</span>')
            target = href(words_of(core)[0]) if href else None
            if target:
                piece = f'<a class="wl" href="{html.escape(target)}">{piece}</a>'
        else:
            piece = html.escape(token)
        out.append(f'<span class="w" style="--i:{i}">{piece}</span>')
    return " ".join(out)
